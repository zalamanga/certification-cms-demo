CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, username VARCHAR(100) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE, password VARCHAR(255) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS blogs (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, title VARCHAR(255) NOT NULL,
 content LONGTEXT NOT NULL, author VARCHAR(150) NOT NULL DEFAULT '',
 featured_image VARCHAR(255) DEFAULT NULL, publish_date DATE DEFAULT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'draft', views INT UNSIGNED NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS skema (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, nama VARCHAR(255) NOT NULL,
 kode VARCHAR(100) NOT NULL UNIQUE, jenis VARCHAR(150) NOT NULL,
 harga DECIMAL(14,2) NOT NULL DEFAULT 0, unit_kompetensi INT NOT NULL DEFAULT 0,
 masa_berlaku VARCHAR(100) NOT NULL DEFAULT '', ringkasan TEXT DEFAULT NULL,
 gambar VARCHAR(255) DEFAULT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS unit_kompetensi (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, skema_id INT UNSIGNED NOT NULL,
 no_urut INT NOT NULL DEFAULT 0, kode_unit VARCHAR(100) NOT NULL DEFAULT '',
 judul_unit VARCHAR(255) NOT NULL DEFAULT '', standar_kompetensi TEXT DEFAULT NULL,
 lampiran_file VARCHAR(255) DEFAULT NULL,
 FOREIGN KEY (skema_id) REFERENCES skema(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS persyaratan (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, skema_id INT UNSIGNED NOT NULL,
 deskripsi TEXT NOT NULL, FOREIGN KEY (skema_id) REFERENCES skema(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS dokumen_persyaratan (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, skema_id INT UNSIGNED NOT NULL,
 nama_dokumen VARCHAR(255) NOT NULL, wajib TINYINT(1) NOT NULL DEFAULT 0,
 FOREIGN KEY (skema_id) REFERENCES skema(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS metode_asesmen (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, skema_id INT UNSIGNED NOT NULL,
 jenis_peserta VARCHAR(150) NOT NULL DEFAULT '', metode VARCHAR(255) NOT NULL DEFAULT '',
 deskripsi TEXT DEFAULT NULL, FOREIGN KEY (skema_id) REFERENCES skema(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS pemeliharaan (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, skema_id INT UNSIGNED NOT NULL,
 deskripsi TEXT NOT NULL, FOREIGN KEY (skema_id) REFERENCES skema(id) ON DELETE CASCADE
);
